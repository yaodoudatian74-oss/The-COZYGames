// ───────── 参照ヘルパー ─────────
export function infoOf(key) {
  const [t, n] = key.split(':');
  const i = Number(n);
  switch (t) {
    case 'furn': return FURNITURE[i];
    case 'fish': return FISH[i];
    case 'bug': return BUGS[i];
    case 'dish': return DISHES[i];
    case 'crop': return CROPS[i];
    case 'tool': return TOOLS[i];
    case 'ore': return ORES[i];
    case 'wood': return WOODS[i];
    case 'seed': {
      const c = CROPS[i];
      return { cat: 'seed', id: key, name: c.name + 'のたね', price: Math.round(c.price * 0.35), seedOf: i };
    }
    default: return null;
  }
}

// 材料として使えるタグ
export function tagsOf(key) {
  const t = key.split(':')[0];
  if (t === 'fish') return ['fish'];
  if (t === 'bug') return ['bug'];
  if (t === 'crop') return [CROPS[Number(key.split(':')[1])].tag];
  return [];
}

export function describe(info) {
  switch (info.cat) {
    case 'fish': return `${info.loc === 'river' ? '川' : info.loc === 'pond' ? '池・湖' : '海'}にすむ。${info.time === 'd' ? '昼' : info.time === 'n' ? '夜' : 'いつでも'}に釣れることが多い。`;
    case 'bug': return `${{ tree: '木', flower: '花', ground: '地面', water: '水辺' }[info.habitat]}でよく見かける。${info.fast ? '飛び回るので素早い。' : 'ゆっくり歩く。'}`;
    case 'dish': return `材料: ${info.tags.map((t) => ({ fish: '魚', bug: '虫', veg: '野菜', fruit: '果物', grain: '穀物', herb: 'ハーブ' })[t]).join('・')}。`;
    case 'crop': return `育つまで${info.growDays}日。${info.mask.split('').map((b, i) => (b === '1' ? '春夏秋冬'[i] : '')).join('')}に育てやすい。`;
    case 'furn': return `${info.fp[0]}×${info.fp[1]}マスを使う家具。`;
    case 'tool': return '道具。なくならないし、売ることはできない。';
    case 'ore': return `${info.rare >= 3 ? 'めずらしい鉱石。' : '鉱石。'}つるはしで岩をほると手に入る。`;
    case 'wood': return `木材。おので木を切ると手に入る。${info.rare >= 3 ? 'とてもめずらしい。' : ''}`;
    default: return '';
  }
}

